"""The reference library: one folder per condition, the same files in every sample.

library/
  <condition>/
    <condition>_01/
      sound.wav             outdoor unit, 10 s, 16 kHz mono          (simulated)
      thermal_indoor.png    radiometric thermal, indoor coil          (simulated)
      thermal_outdoor.png   radiometric thermal, outdoor unit         (simulated)
      sensors.csv           30 minutes of readings, one row a minute  (simulated)
      info.json             condition, severity, source of every file
    photos/                 photos of this fault (drop your own here)
      photos.json           source of each photo: real-photo, chatgpt or muse-image

Build:  python -m faultlens.library --per-condition 3
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import knowledge, render, sensors, simulate

ROOT = Path(__file__).resolve().parent.parent
LIBRARY = ROOT / "library"
SIGNAL_FILES = {
    "sound": "sound.wav",
    "thermal_indoor": "thermal_indoor.png",
    "thermal_outdoor": "thermal_outdoor.png",
    "sensors": "sensors.csv",
}
PHOTO_SOURCES = ("real-photo", "chatgpt", "muse-image")


def build(per_condition: int = 3) -> None:
    severities = [1.0, 0.6, 0.3, 0.8, 0.45]
    for ci, cond in enumerate(simulate.CONDITIONS):
        for i in range(per_condition):
            sev = 1.0 if cond == "normal" else severities[i % len(severities)]
            seed = 50_000_000 + ci * 1000 + i
            d = LIBRARY / cond / f"{cond}_{i + 1:02d}"
            d.mkdir(parents=True, exist_ok=True)
            (d / "sound.wav").write_bytes(render.write_wav(simulate.sound(cond, seed=seed, severity=sev)))
            (d / "thermal_indoor.png").write_bytes(
                render.write_thermal_png(simulate.thermal_indoor(cond, seed=seed, severity=sev)))
            (d / "thermal_outdoor.png").write_bytes(
                render.write_thermal_png(simulate.thermal_outdoor(cond, seed=seed, severity=sev)))
            (d / "sensors.csv").write_text(sensors.to_csv(sensors.generate(cond, seed=seed, severity=sev)))
            (d / "info.json").write_text(json.dumps({
                "condition": cond,
                "severity": sev,
                "seed": seed,
                "sources": {k: "simulated" for k in SIGNAL_FILES},
                "note": "Generated by faultlens/simulate.py and faultlens/sensors.py from simple physical "
                        "models of each fault. Not a field recording.",
            }, indent=1))
        photos = LIBRARY / cond / "photos"
        photos.mkdir(parents=True, exist_ok=True)
        meta = photos / "photos.json"
        if not meta.exists():
            meta.write_text(json.dumps({}, indent=1))
    print(f"Library written to {LIBRARY}")


def _photo_list(cond: str) -> list[dict]:
    folder = LIBRARY / cond / "photos"
    if not folder.exists():
        return []
    try:
        meta = json.loads((folder / "photos.json").read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        meta = {}
    out = []
    for p in sorted(folder.iterdir()):
        if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp"):
            out.append({"file": p.name, "url": f"/library/{cond}/photos/{p.name}",
                        "source": meta.get(p.name, "unlabelled")})
    return out


def listing() -> list[dict]:
    """Everything the Explore view needs, without reading the signal files."""
    titles = {f["fault_id"]: f for f in knowledge.fault_menu()}
    out = []
    for cond in simulate.CONDITIONS:
        folder = LIBRARY / cond
        samples = []
        if folder.exists():
            for d in sorted(p for p in folder.iterdir() if p.is_dir() and p.name != "photos"):
                info = json.loads((d / "info.json").read_text()) if (d / "info.json").exists() else {}
                samples.append({
                    "id": d.name,
                    "severity": info.get("severity"),
                    "sources": info.get("sources", {}),
                    "files": {k: f"/library/{cond}/{d.name}/{v}" for k, v in SIGNAL_FILES.items()
                              if (d / v).exists()},
                })
        meta = titles.get(cond, {})
        out.append({"condition": cond, "title": meta.get("title", cond), "summary": meta.get("summary", ""),
                    "samples": samples, "photos": _photo_list(cond)})
    return out


def sample_dir(cond: str, sample: str) -> Path:
    d = (LIBRARY / cond / sample).resolve()
    if LIBRARY.resolve() not in d.parents or not d.is_dir():
        raise FileNotFoundError(f"{cond}/{sample}")
    return d


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-condition", type=int, default=3)
    build(ap.parse_args().per_condition)
